--  سامانه املاک — پایگاه داده (Supabase / PostgreSQL)
--  این فایل را یک‌بار در Supabase → SQL Editor اجرا کنید.
--  تمام دسترسی‌ها همین‌جا (سمت سرور) با Row Level Security کنترل می‌شود؛
--  یعنی حتی اگر کسی کد اپ را دستکاری کند، نمی‌تواند از نقش خودش فراتر برود.
--
--  نقش‌ها:
--    admin    ادمین اصلی: دسترسی کامل به همه‌چیز
--    agent    مشاور: ثبت و ویرایش فقط آگهی‌های خودش، دیدن درخواست‌های مشتریانِ آگهی‌های خودش
--    pending  ثبت‌نام کرده ولی هنوز ادمین تأییدش نکرده (هیچ دسترسی ندارد)
--    (مشتری)  بدون ورود؛ فقط آگهی‌های فعال و طراحی‌ها را می‌بیند و می‌تواند درخواست بازدید بفرستد
--
--  اولین کسی که در اپ ثبت‌نام کند خودکار «ادمین اصلی» می‌شود.
-- =====================================================================

-- ---------- پروفایل کاربران ----------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text,
  full_name   text not null default '',
  phone       text not null default '',
  bio         text not null default '',
  role        text not null default 'pending' check (role in ('admin','agent','pending')),
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id = auth.uid() and role = 'admin' and active)
$$;

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id = auth.uid() and role in ('admin','agent') and active)
$$;

-- ساخت خودکار پروفایل بعد از ثبت‌نام؛ اولین کاربر = ادمین
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- قفل تا دو ثبت‌نام هم‌زمان هر دو ادمین نشوند
  perform pg_advisory_xact_lock(724001);
  insert into profiles (id, email, full_name, phone, role)
  values (
    new.id, new.email,
    coalesce(new.raw_user_meta_data->>'full_name',''),
    coalesce(new.raw_user_meta_data->>'phone',''),
    case when exists(select 1 from profiles where role = 'admin') then 'pending' else 'admin' end
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- فقط ادمین می‌تواند نقش یا وضعیت فعال بودن را تغییر دهد
create or replace function public.protect_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then
    new.role := old.role;
    new.active := old.active;
  end if;
  new.email := old.email;
  return new;
end $$;

drop trigger if exists protect_profile on public.profiles;
create trigger protect_profile before update on public.profiles
  for each row execute function public.protect_profile();

alter table public.profiles enable row level security;
drop policy if exists "profiles read"   on public.profiles;
drop policy if exists "profiles update" on public.profiles;
drop policy if exists "profiles delete" on public.profiles;
create policy "profiles read"   on public.profiles for select using (id = auth.uid() or is_admin());
create policy "profiles update" on public.profiles for update using (id = auth.uid() or is_admin());
create policy "profiles delete" on public.profiles for delete using (is_admin() and id <> auth.uid());

-- کارت عمومی مشاور (بدون ایمیل) برای نمایش زیر آگهی‌ها
create or replace view public.public_agents as
  select id, full_name, phone, bio from public.profiles
  where role in ('admin','agent') and active;
grant select on public.public_agents to anon, authenticated;

-- ---------- آگهی‌ها ----------
create table if not exists public.listings (
  id           bigint generated by default as identity primary key,
  agent_id     uuid not null default auth.uid() references public.profiles(id) on delete restrict,
  deal         text not null check (deal in ('sale','rent')),
  ptype        text not null default 'apartment'
               check (ptype in ('apartment','villa','land','commercial','office','garden')),
  title        text not null,
  city         text not null default '',
  district     text not null default '',
  price        bigint,          -- قیمت کل (فروش) به تومان
  deposit      bigint,          -- رهن / ودیعه (اجاره) به تومان
  rent         bigint,          -- اجاره ماهانه به تومان
  area         int,             -- متراژ بنا
  land_area    int,             -- متراژ زمین
  rooms        int,
  floor        int,
  floors       int,
  year_built   int,             -- سال ساخت (شمسی)
  features     text[] not null default '{}',
  description  text not null default '',
  images       text[] not null default '{}',
  status       text not null default 'active'
               check (status in ('active','reserved','sold','rented','hidden')),
  featured     boolean not null default false,   -- آگهی ویژه (فقط ادمین)
  verified     boolean not null default false,   -- نشان «تأیید شده» (فقط ادمین)
  views        int not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists listings_agent_idx on public.listings(agent_id);
create index if not exists listings_deal_idx  on public.listings(deal, status);

create or replace function public.touch_listing() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- افزایش شمارنده بازدید از طریق inc_views؛ به چیز دیگری دست نزن
  if tg_op = 'UPDATE' and current_setting('amlak.inc_views', true) = 'on' then
    return new;
  end if;
  new.updated_at := now();
  -- مشاور نمی‌تواند آگهی را به اسم مشاور دیگری بزند یا «ویژه» کند؛ فقط ادمین
  if not is_admin() then
    if tg_op = 'INSERT' then
      new.agent_id := auth.uid();
      new.featured := false;
      new.verified := false;
      new.views := 0;
    else
      new.agent_id := old.agent_id;
      new.featured := old.featured;
      new.verified := old.verified;
      new.views := old.views;
    end if;
  end if;
  return new;
end $$;
drop trigger if exists touch_listing on public.listings;
create trigger touch_listing before insert or update on public.listings
  for each row execute function public.touch_listing();

alter table public.listings enable row level security;
drop policy if exists "listings public read" on public.listings;
drop policy if exists "listings staff read"  on public.listings;
drop policy if exists "listings insert"      on public.listings;
drop policy if exists "listings update"      on public.listings;
drop policy if exists "listings delete"      on public.listings;
-- مشتری‌ها فقط آگهی‌های فعال/رزرو شده را می‌بینند
create policy "listings public read" on public.listings for select using (status in ('active','reserved'));
-- مشاور همه آگهی‌های خودش را (حتی مخفی/فروخته‌شده) می‌بیند؛ ادمین همه را
create policy "listings staff read"  on public.listings for select using ((agent_id = auth.uid() and is_staff()) or is_admin());
create policy "listings insert"      on public.listings for insert with check (is_staff());
create policy "listings update"      on public.listings for update using ((agent_id = auth.uid() and is_staff()) or is_admin());
create policy "listings delete"      on public.listings for delete using ((agent_id = auth.uid() and is_staff()) or is_admin());

-- شمارنده بازدید (مشتری ناشناس هم می‌تواند فقط یکی اضافه کند)
create or replace function public.inc_views(lid bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform set_config('amlak.inc_views', 'on', true);
  update listings set views = views + 1 where id = lid and status in ('active','reserved');
  perform set_config('amlak.inc_views', 'off', true);
end $$;
grant execute on function public.inc_views(bigint) to anon, authenticated;

-- ---------- اطلاعات محرمانه ملک (مالک، آدرس دقیق) ----------
-- فقط مشاورِ همان آگهی و ادمین می‌بینند؛ مشتری هرگز.
create table if not exists public.listing_private (
  listing_id     bigint primary key references public.listings(id) on delete cascade,
  owner_name     text not null default '',
  owner_phone    text not null default '',
  exact_address  text not null default '',
  notes          text not null default ''
);
alter table public.listing_private enable row level security;
drop policy if exists "private all" on public.listing_private;
create policy "private all" on public.listing_private for all
  using (is_admin() or exists(select 1 from listings l where l.id = listing_id and l.agent_id = auth.uid() and is_staff()))
  with check (is_admin() or exists(select 1 from listings l where l.id = listing_id and l.agent_id = auth.uid() and is_staff()));

-- ---------- درخواست‌های مشتری (Lead) ----------
-- مشتری بدون ثبت‌نام درخواست بازدید/تماس می‌فرستد و مستقیم به مشاورِ همان آگهی می‌رسد.
create table if not exists public.leads (
  id          bigint generated by default as identity primary key,
  listing_id  bigint references public.listings(id) on delete cascade,
  name        text not null check (char_length(name) between 2 and 80),
  phone       text not null check (char_length(phone) between 7 and 20),
  message     text not null default '' check (char_length(message) <= 1000),
  status      text not null default 'new' check (status in ('new','contacted','closed')),
  created_at  timestamptz not null default now()
);
alter table public.leads enable row level security;
drop policy if exists "leads insert" on public.leads;
drop policy if exists "leads read"   on public.leads;
drop policy if exists "leads update" on public.leads;
drop policy if exists "leads delete" on public.leads;
create policy "leads insert" on public.leads for insert to anon, authenticated
  with check (status = 'new' and exists(select 1 from listings l where l.id = listing_id and l.status in ('active','reserved')));
create policy "leads read"   on public.leads for select using (is_admin() or exists(select 1 from listings l where l.id = listing_id and l.agent_id = auth.uid() and is_staff()));
create policy "leads update" on public.leads for update using (is_admin() or exists(select 1 from listings l where l.id = listing_id and l.agent_id = auth.uid() and is_staff()));
create policy "leads delete" on public.leads for delete using (is_admin());

